/**
 * Deterministic chunk generator for mock files.
 */
export function generateMockChunks(totalChunks: number, ratioVerified = 0.75): ChunkInfo[] {
  const chunks: ChunkInfo[] = [];
  const verifiedCount = Math.floor(totalChunks * ratioVerified);
  const inFlightCount = Math.min(Math.floor(totalChunks * 0.1), 8);

  for (let i = 0; i < totalChunks; i++) {
    let status: ChunkInfo['status'] = 'missing';
    if (i < verifiedCount) {
      status = 'verified';
    } else if (i < verifiedCount + inFlightCount) {
      status = 'in_flight';
    } else if (i === verifiedCount + inFlightCount && Math.random() > 0.8) {
      status = 'corrupt';
    }

    const simulatedHash = `sim_chk_${(i).toString().padStart(4, '0')}_${(i * 1337).toString(16).padStart(4, '0')}7b9d4e21${(i * 7).toString(16).padStart(4, '0')}`;

    chunks.push({
      index: i,
      chunkSha256: simulatedHash,
      hash: simulatedHash,
      sizeBytes: 1048576, // 1 MiB
      status,
      seederCount: Math.floor(3 + (i % 7)),
      lastSourcePeer: status === 'verified' ? `peer-${(i % 5) + 1}` : undefined,
      isSimulatedVerification: true,
    });
  }
  return chunks;
}

