import React, { useState } from 'react';
import type { ActivityLogEntry, LogSeverity, ScreenId } from '../types';
import { SearchIcon, TerminalIcon } from '../components/icons/Icons';
import { formatTimestamp } from '../utils';

interface ActivityLogsPageProps {
  logs: ActivityLogEntry[];
  onNavigate: (screen: ScreenId) => void;
}

export const ActivityLogsPage: React.FC<ActivityLogsPageProps> = ({
  logs,
}) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [severityFilter, setSeverityFilter] = useState<LogSeverity | 'all'>('all');
  const [componentFilter, setComponentFilter] = useState<string>('all');

  const filteredLogs = logs.filter((log) => {
    const matchesSearch =
      log.event.toLowerCase().includes(searchQuery.toLowerCase()) ||
      log.details.toLowerCase().includes(searchQuery.toLowerCase()) ||
      (log.peerId && log.peerId.toLowerCase().includes(searchQuery.toLowerCase())) ||
      (log.fileId && log.fileId.toLowerCase().includes(searchQuery.toLowerCase()));

    const matchesSeverity = severityFilter === 'all' || log.severity === severityFilter;
    const matchesComponent = componentFilter === 'all' || log.component === componentFilter;

    return matchesSearch && matchesSeverity && matchesComponent;
  });

  const handleExportLogs = () => {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(filteredLogs, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', `p2p_edge_activity_logs_${Date.now()}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  return (
    <div className="page-container activity-logs-page">
      {/* Simulation Banner */}
      <div className="sim-notice-banner" role="region" aria-label="Simulation Notice">
        <div className="notice-icon">ℹ</div>
        <div className="notice-content">
          <strong>Simulated Event Audit Trail:</strong> Events displayed below represent real-time
          system signals generated by WebRTC DataChannel state transitions, ICE candidate exchanges, and
          cryptographic chunk verification.
        </div>
      </div>

      {/* Control Toolbar */}
      <div className="library-toolbar">
        <div className="search-box">
          <SearchIcon size={18} className="search-icon" />
          <input
            type="search"
            className="search-input"
            placeholder="Search events, components, peer IDs or hash codes..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            aria-label="Search logs"
          />
        </div>

        <div className="filter-group">
          <label htmlFor="log-sev-select" className="filter-label">Severity:</label>
          <select
            id="log-sev-select"
            className="filter-select"
            value={severityFilter}
            onChange={(e) => setSeverityFilter(e.target.value as LogSeverity | 'all')}
          >
            <option value="all">All Severities ({logs.length})</option>
            <option value="INFO">INFO</option>
            <option value="WARN">WARN</option>
            <option value="ERROR">ERROR</option>
            <option value="DEBUG">DEBUG</option>
          </select>
        </div>

        <div className="filter-group">
          <label htmlFor="log-comp-select" className="filter-label">Component:</label>
          <select
            id="log-comp-select"
            className="filter-select"
            value={componentFilter}
            onChange={(e) => setComponentFilter(e.target.value)}
          >
            <option value="all">All Components</option>
            <option value="Scheduler">Scheduler</option>
            <option value="DataChannel">DataChannel</option>
            <option value="Signaling">Signaling</option>
            <option value="Storage">Storage</option>
            <option value="Verifier">Verifier</option>
          </select>
        </div>

        <button
          type="button"
          className="btn btn-secondary"
          onClick={handleExportLogs}
          title="Export filtered logs as JSON"
        >
          <TerminalIcon size={16} />
          <span>Export JSON Audit</span>
        </button>
      </div>

      {/* Logs Table */}
      <div className="table-responsive-wrapper">
        <table className="data-table monospace-text" aria-label="Activity Audit Trail">
          <thead>
            <tr>
              <th>Timestamp</th>
              <th>Severity</th>
              <th>Subsystem</th>
              <th>Event Code</th>
              <th>Referenced Entities</th>
              <th>Event Description &amp; Payload</th>
            </tr>
          </thead>
          <tbody>
            {filteredLogs.length === 0 ? (
              <tr>
                <td colSpan={6} className="empty-table-cell">
                  <div className="empty-state-box">
                    <p className="empty-title">No audit records match filters</p>
                    <button
                      type="button"
                      className="btn btn-secondary"
                      onClick={() => {
                        setSearchQuery('');
                        setSeverityFilter('all');
                        setComponentFilter('all');
                      }}
                    >
                      Clear Log Filters
                    </button>
                  </div>
                </td>
              </tr>
            ) : (
              filteredLogs.map((log) => (
                <tr key={log.id}>
                  <td className="log-time-cell">
                    {formatTimestamp(log.timestamp)}
                  </td>
                  <td>
                    <span className={`log-badge ${log.severity.toLowerCase()}`}>
                      {log.severity}
                    </span>
                  </td>
                  <td>
                    <span className="subsystem-pill">[{log.component}]</span>
                  </td>
                  <td>
                    <strong className="event-code-text">{log.event}</strong>
                  </td>
                  <td>
                    <div className="entities-cell">
                      {log.peerId && <span className="entity-tag peer">{log.peerId}</span>}
                      {log.fileId && <span className="entity-tag file">{log.fileId}</span>}
                      {!log.peerId && !log.fileId && <span className="entity-tag none">global</span>}
                    </div>
                  </td>
                  <td className="log-details-cell">
                    {log.details}
                  </td>
                </tr>
              ))
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
};
